// The scene arrives in the page a little at a time (Polys lesson, 2026-10-29): wait for the object list to stop growing.
let sceneRegisteredPromise = null;
function sceneRegistered(scene) {
    if (sceneRegisteredPromise) return sceneRegisteredPromise;
    sceneRegisteredPromise = new Promise((resolve) => {
        const t0 = Date.now();
        let last = -1, steadyMs = 0;
        const iv = setInterval(() => {
            const n = Object.keys(scene.objects || {}).length;
            if (n > 0 && n === last) steadyMs += 250; else { steadyMs = 0; last = n; }
            if (steadyMs >= 1500 || Date.now() - t0 > 30000) {
                clearInterval(iv);
                console.log("[Sphererebro] scene registered:", n, "objects, after", ((Date.now() - t0) / 1000).toFixed(1), "s");
                resolve();
            }
        }, 250);
    });
    return sceneRegisteredPromise;
}
async function findWait(scene, name, ms) {
    const t0 = Date.now();
    for (;;) {
        let o = null;
        try { o = await scene.Find(name); } catch (e) { }
        if (o) return o;
        if (Date.now() - t0 > (ms || 10000)) return null;
        await new Promise((r) => setTimeout(r, 250));
    }
}
const clamp = (v, a, b) => Math.max(a, Math.min(b, v));
const ease = (s) => s * s * (3 - 2 * s);

// Pure state helpers (exported for the tests in ../Assets/tests).
const SBState = {
    // dais: "yaw0|rate|t0|tEnd|target" -> yaw at time t (degrees, unbounded). A timed move (tEnd > 0) lands exactly
    // on its target.
    daisYaw(raw, t) {
        if (!raw) return 0;
        const [yaw0, rate, t0, tEnd, target] = String(raw).split("|").map(Number);
        const start = Number.isFinite(t0) ? t0 : t;
        if (tEnd > 0 && t >= tEnd && Number.isFinite(target)) return target;
        const end = tEnd > 0 ? tEnd : Infinity;
        return (yaw0 || 0) + (rate || 0) * (clamp(t, start, end) - start) / 1000;
    },
    // turning now? (a finished timed move isn't)
    daisTurning(raw, t) {
        if (!raw) return false;
        const [, rate, , tEnd] = String(raw).split("|").map(Number);
        return !!rate && !(tEnd > 0 && t >= tEnd);
    },
    daisRaw(yaw0, rate, t0, tEnd, target) {
        const parts = [Number(yaw0.toFixed(3)), rate, Math.round(t0), tEnd ? Math.round(tEnd) : 0];
        if (target !== undefined) parts.push(target);
        return parts.join("|");
    },
    // the shortest turn from yaw to 0, as a timed move at `rate`
    homeMove(yaw, rate, t) {
        const y = ((yaw % 360) + 540) % 360 - 180;            // -180..180
        if (Math.abs(y) < 0.05) return SBState.daisRaw(0, 0, t, 0);
        const r = y > 0 ? -rate : rate;
        return SBState.daisRaw(y, r, t, t + Math.abs(y) / rate * 1000, 0);
    },
    // a two-phase move (vertical, then along z) between "out" and "in"; s = 0 at out, 1 at in
    moveProgress(raw, t, totalS) {
        if (!raw) return { dir: "out", s: 0 };
        const [dir, t0] = String(raw).split("|");
        const p = clamp((t - Number(t0)) / (totalS * 1000), 0, 1);
        return { dir, s: dir === "in" ? p : 1 - p, done: p >= 1 };
    },
    // where a segment is at progress s (0 out .. 1 in): retracting drops first then slides; extending slides then rises
    segmentPose(outZ, inZ, inY, dropS, slideS, s) {
        const total = dropS + slideS, k = s * total;
        const y = k <= dropS ? inY * ease(k / dropS) : inY;
        const z = k <= dropS ? outZ : outZ + (inZ - outZ) * ease((k - dropS) / slideS);
        return { y, z };
    },
    // lighting preset id from state (House when unset or unknown), and the next one for the LIGHTS key
    lx(raw, cfg) { return cfg.order.indexOf(raw) >= 0 ? raw : "house"; },
    lxNext(raw, cfg) { const o = cfg.order; return o[(o.indexOf(SBState.lx(raw, cfg)) + 1) % o.length]; },
};
