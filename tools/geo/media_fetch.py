"""Public media modules, step 1: take the outlets from the atlas package and bake the name cards.

Run (system Python 3.12 with Pillow):  python tools/geo/media_fetch.py [path to the atlas package's layers/media.json]
Reads   the Public Hyperscale atlas package's layers/media.json (Ben's own data package; default path below)
Writes  tools/geo/media_data.json     the tour's stops (the package's 14 "broadcasters") and every outlet in the State
                                      Media Monitor survey as packaged (city, lat, lon, typology group)
        talk/gen/media_cards.png      one 2048 x 2048 atlas of name cards for the tour (warm, small: CLAUDE.md rule 12)

Nothing is downloaded. The numbers on stage are whatever the package holds: on 2026-11-10 that is 586 outlets, 17 of them
"Independent public" (the deck's slide says 606 and 19, State Media Monitor's own 2025 totals).
"""
import json, os, sys
from PIL import Image, ImageDraw, ImageFont

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, "..", ".."))
SRC = sys.argv[1] if len(sys.argv) > 1 else r"D:\Academy\Ben-Presentations\Public Hyperscale\Assets\StreamingAssets\AtlasPackage\layers\media.json"
# the tour's order: out from London across Europe, east through Asia, south, then home across the Atlantic
ORDER = ["BBC", "RTÉ", "ARTE", "RAI", "SVT", "Al Jazeera", "Prasar Bharati", "KBS", "NHK", "ABC", "SABC", "EBC / TV Brasil", "PBS", "CBC / Radio-Canada"]
GROUP = {"SC": "captured", "CaPu": "captured", "CaPr": "captured", "ISFM": "mixed", "ISF": "mixed", "ISM": "mixed", "IP": "independent", "U": "unknown"}
CARD_W, CARD_H, COLS = 1024, 256, 2

d = json.load(open(SRC, encoding="utf-8"))
by = {b["name"]: b for b in d["broadcasters"]}
missing = [n for n in ORDER if n not in by]
if missing: raise SystemExit("the package has no broadcaster named: " + ", ".join(missing))
stops = []
for k, n in enumerate(ORDER):
    b = by[n]
    city = b["city"].split(",")[0] if b["city"].startswith("Shibuya") is False else "Tokyo"
    country = b["country"].split(" (")[0].replace("France / Germany", "France and Germany")
    stops.append({"name": n.replace(" / ", " · "), "city": city, "country": country, "founded": b["founded"],
                  "lat": b["lat"], "lon": b["lon"], "card": [k % COLS, k // COLS]})

outlets = []
for c in d["clusters"]:
    for i in c["items"]:
        outlets.append({"lat": c["lat"], "lon": c["lon"], "city": c["city"], "group": GROUP.get(i["typology"], "unknown")})
count = {}
for o in outlets: count[o["group"]] = count.get(o["group"], 0) + 1

# ---------------------------------------------------------------- the cards
big = ImageFont.truetype(r"C:\Windows\Fonts\seguisb.ttf", 118)
small = ImageFont.truetype(r"C:\Windows\Fonts\segoeui.ttf", 62)
atlas = Image.new("RGBA", (2048, 2048), (0, 0, 0, 0))
for s in stops:
    im = Image.new("RGBA", (CARD_W, CARD_H), (0, 0, 0, 0)); dr = ImageDraw.Draw(im)
    f = big
    while dr.textlength(s["name"], font=f) > CARD_W - 40: f = ImageFont.truetype(r"C:\Windows\Fonts\seguisb.ttf", f.size - 6)
    dr.text((CARD_W / 2, 92), s["name"], font=f, fill=(255, 196, 110, 235), anchor="ms")          # warm gold, not white
    line = f"{s['city']}, {s['country']}  ·  {s['founded']}"
    f2 = small
    while dr.textlength(line, font=f2) > CARD_W - 40: f2 = ImageFont.truetype(r"C:\Windows\Fonts\segoeui.ttf", f2.size - 4)
    dr.text((CARD_W / 2, 190), line, font=f2, fill=(222, 170, 110, 200), anchor="ms")
    atlas.alpha_composite(im, (s["card"][0] * CARD_W, s["card"][1] * CARD_H))
os.makedirs(os.path.join(REPO, "talk", "gen"), exist_ok=True)
atlas.save(os.path.join(REPO, "talk", "gen", "media_cards.png"))

# the AI data centers layer of the same package (layers/compute.json "ai": Epoch AI's list as packaged), for media_capture
# (Ben, 2026-11-10: "Now add the AI Data centers layer, bake that in")
comp = json.load(open(os.path.join(os.path.dirname(SRC), "compute.json"), encoding="utf-8"))
ai = [{"lat": a["lat"], "lon": a["lon"], "mw": a.get("mw") or 0} for a in comp["ai"]]

out = {"_readme": "GENERATED by tools/geo/media_fetch.py from the atlas package's layers/media.json: do not edit.",
       "source": "State Media Monitor (statemediamonitor.com) as packaged in the Public Hyperscale atlas; broadcasters: the package's own list",
       "stops": stops, "cardGrid": [COLS, 2048 // CARD_H], "cardPx": [CARD_W, CARD_H], "counts": count, "outlets": outlets, "ai": ai}
json.dump(out, open(os.path.join(HERE, "media_data.json"), "w", encoding="utf-8"), ensure_ascii=False, separators=(",", ":"))
print(f"AI data centers: {len(ai)}"); print(f"media: {len(stops)} tour stops; {len(outlets)} outlets in {len(d['clusters'])} cities: {count}")
