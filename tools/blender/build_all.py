"""Rebuild every talk asset in one run, each in a fresh headless Blender, then write talk/models/ASSET_REPORT.md.
Run (any Python, e.g. Blender's):  <blender python> tools/blender/build_all.py [--no-preview] [asset_script ...]
"""
import glob, json, os, subprocess, sys, time

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, "..", ".."))
# The newest Blender 5.x installed (5.2 on Yoda-VIII, 5.1 on Yoda-IX); BLENDER in the environment overrides.
BLENDER = os.environ.get("BLENDER") or sorted(glob.glob(r"C:\Program Files\Blender Foundation\Blender 5.*\blender.exe"),
                                              key=lambda p: [int(x) for x in os.path.basename(os.path.dirname(p)).split()[-1].split(".")])[-1]
SCRIPTS = ["white_room", "server_rack", "server_rack_far", "electricity_bill", "stamp", "light_beam", "curved_screen", "radio_1920s",
           "tv_midcentury", "web_monitor_1990s", "feed_tile", "devices", "water_tank", "gas_plant", "commons_halls", "talk_text"]
args = [a for a in sys.argv[1:] if not a.startswith("--")]
extra = [a for a in sys.argv[1:] if a.startswith("--")]
todo = args or SCRIPTS
report = os.path.join(REPO, "talk", "models", "report.jsonl")
if not args and os.path.exists(report): os.remove(report)
failed = []
for s in todo:
    t0 = time.time()
    r = subprocess.run([BLENDER, "-b", "--factory-startup", "--python", os.path.join(HERE, s + ".py"), "--"] + extra,
                       capture_output=True, text=True, cwd=REPO)
    ok = r.returncode == 0 and "Traceback" not in (r.stdout + r.stderr)
    print(f"{'ok  ' if ok else 'FAIL'} {s:20s} {time.time() - t0:5.0f}s")
    if not ok: failed.append(s); print((r.stdout + r.stderr)[-1500:])

rows = {}
for line in open(report):
    d = json.loads(line); rows[d["asset"]] = d
md = ["# Talk asset report", "", f"Generated by tools/blender/build_all.py, {time.strftime('%Y-%m-%d %H:%M')}. One line per asset (the latest build).",
      "GLB = glTF 2.0 binary (Y up, metres, origin at the base centre, textures embedded as JPEG); the FBX copy in",
      "Assets/_Sphererebro/Talk/Models/ is what Unity uses. LOD1 (~40% triangles) is made for anything over 20,000 triangles.", "",
      "| Asset | Triangles | GLB size | Note |", "|---|---:|---:|---|"]
for k in sorted(rows):
    d = rows[k]
    md.append(f"| {k} | {d['tris']:,} | {d['bytes'] / 1048576:.1f} MB | {d.get('note', '')} |")
if failed: md += ["", "FAILED: " + ", ".join(failed)]
open(os.path.join(REPO, "talk", "models", "ASSET_REPORT.md"), "w").write("\n".join(md) + "\n")
print("report written; failed:", failed or "none")
sys.exit(1 if failed else 0)
