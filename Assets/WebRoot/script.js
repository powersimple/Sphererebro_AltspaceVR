if (typeof window !== "undefined" && window.addEventListener) window.addEventListener("bs-loaded", async () => {
    const scene = BS.Scene.GetInstance();
    await scene.WaitForUnityLoaded();
    await sceneRegistered(scene);
    const cfg = SB.props;
    const names = [];
    for (let i = 1; i <= cfg.flutes; i++) names.push("Champagne Flute " + String(i).padStart(2, "0"));
    for (let i = 1; i <= cfg.bottles; i++) names.push("Beer Bottle " + String(i).padStart(2, "0"));
    let found = 0;
    for (const n of names) {
        const body = await scene.Find(n), home = await scene.Find(n + " Home");
        if (!body || !home) continue;
        found++;
        goesHome(body, home);
    }
    console.log("[Sphererebro]", found, "grabbables watched");

    async function goesHome(body, homeObject) {
        const sync = body.GetComponent(BS.CT.SyncedObject);
        const rigidbody = body.GetComponent(BS.CT.Rigidbody);
        let home = null, pos = null, held = false, awaySince = null;
        await homeObject.WatchTransform([BS.PN.position, BS.PN.rotation], (t) => { home = { p: t.position, r: t.rotation }; });
        await body.WatchTransform([BS.PN.position], (t) => { pos = t.position; });
        body.On("grab", () => { held = true; awaySince = null; });
        body.On("drop", () => { held = false; });
        const dist = (a, b) => Math.hypot(a.x - b.x, a.y - b.y, a.z - b.z);
        async function back() {
            if (sync) {
                sync.TakeOwnership();
                for (let i = 0; i < 20 && !(await sync.DoIOwn()); i++) await new Promise((r) => setTimeout(r, 100));
                if (!(await sync.DoIOwn())) return false;
            }
            if (rigidbody) { rigidbody.velocity = new BS.Vector3(0, 0, 0); rigidbody.angularVelocity = new BS.Vector3(0, 0, 0); }
            await body.SetPosition(home.p.x, home.p.y, home.p.z);
            await body.SetRotation(home.r);
            return true;
        }
        async function tick() {
            try {
                if (home && pos && !held) {
                    if (dist(pos, home.p) <= cfg.homeRadius) awaySince = null;
                    else if (awaySince === null) awaySince = Date.now();
                    else if ((Date.now() - awaySince) / 1000 >= cfg.returnSeconds && await back()) awaySince = null;
                }
            } catch (e) { console.log("[Sphererebro] prop tick", e); }
            setTimeout(tick, cfg.pollMs);
        }
        tick();
    }
});

