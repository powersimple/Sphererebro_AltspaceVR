"""Images and sound for the module "stills" (tools/talk/modules/stills.py): Ben's own pictures, shown large on a key.
Ben, 2026-11-10: "add some static images that I can trigger with a button".

Run (system Python with Pillow; ffmpeg on the path):  python tools/geo/stills_art.py
Reads   tools/stills/<name>.(png|webp|jpg)   one picture per still named in STILLS below; a missing one is left out
        tools/stills/stewart_voice.mp3       the clip the Stewart key plays
Writes  talk/gen/still_<name>.png            at most 2048 px on the long side (Quest)
        tools/geo/stills_data.json           which stills exist and their sizes (the Blender asset and the module read it)
        Assets/_Sphererebro/Talk/Audio/still_stewart_voice.wav   the clip with a hall's resonance added (early
                                             reflections and a tail: Ben, "add some spatial audio resonance")
"""
import json, os, subprocess
from PIL import Image, ImageFilter

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, "..", ".."))
SRC = os.path.join(REPO, "tools", "stills")
STILLS = ["innovation", "venus", "stewart"]
# Ben, 2026-11-10 (Stewart): "depth map it and make it look 3d". No depth model is installed here, so the depth is drawn
# from the picture itself, which suits a flash-lit face on black: the lit subject's soft silhouette swells toward the
# viewer (a dome), the brighter parts (nose, brow, cheek) a little further, the black background stays at the back, and
# everything below `flat_below` (the caption) is one flat plate just in front of the background.
RELIEF = {"stewart": {"flat_below": 0.80}}


def depth_of(im, flat_below):
    g = im.convert("L"); w, h = g.size
    subject = g.point(lambda v: 255 if v > 30 else 0)
    dome = subject.filter(ImageFilter.GaussianBlur(h * 0.02)).filter(ImageFilter.GaussianBlur(h * 0.085))
    detail = g.filter(ImageFilter.GaussianBlur(h * 0.012))
    d = Image.blend(dome, detail, 0.3)
    plate = Image.new("L", (w, h), 40)                           # the caption's plate
    mask = Image.new("L", (w, h), 0); mask.paste(255, (0, int(h * flat_below), w, h))
    d = Image.composite(plate, d, mask.filter(ImageFilter.GaussianBlur(h * 0.02)))
    lo, hi = d.getextrema()
    d = d.point(lambda v: int(255 * (v - lo) / max(1, hi - lo)))
    return d.resize((256, round(256 * h / w)), Image.LANCZOS)

out = {"_readme": "GENERATED by tools/geo/stills_art.py: do not edit.", "stills": {}}
for name in STILLS:
    src = next((os.path.join(SRC, name + e) for e in (".png", ".webp", ".jpg", ".jpeg") if os.path.exists(os.path.join(SRC, name + e))), None)
    if not src: print(f"  {name}: no picture in tools/stills (left out)"); continue
    im = Image.open(src).convert("RGBA")
    if max(im.size) > 2048: im.thumbnail((2048, 2048), Image.LANCZOS)
    im.save(os.path.join(REPO, "talk", "gen", f"still_{name}.png"))
    out["stills"][name] = {"w": im.size[0], "h": im.size[1]}
    if name in RELIEF:
        depth_of(im, RELIEF[name]["flat_below"]).save(os.path.join(REPO, "talk", "gen", f"still_{name}_depth.png"))
        out["stills"][name]["depth"] = f"still_{name}_depth.png"
    print(f"  {name}: {im.size[0]} x {im.size[1]}")

voice = os.path.join(SRC, "stewart_voice.mp3")
if os.path.exists(voice):
    wav = os.path.join(REPO, "Assets", "_Sphererebro", "Talk", "Audio", "still_stewart_voice.wav")
    # dry voice + early reflections (23..97 ms) + a soft tail (180..520 ms); the level is brought back afterwards
    fx = ("aecho=0.9:0.85:23|41|67|97:0.30|0.24|0.18|0.14,"
          "aecho=0.9:0.9:180|290|410|520:0.22|0.17|0.12|0.08,"
          "apad=pad_dur=1.2,loudnorm=I=-16:TP=-1.5")
    subprocess.run(["ffmpeg", "-y", "-v", "error", "-i", voice, "-af", fx, "-ar", "44100", "-ac", "2", "-c:a", "pcm_s16le", wav], check=True)
    dur = float(subprocess.run(["ffprobe", "-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0", wav], capture_output=True, text=True).stdout)
    out["voice"] = {"clip": "still_stewart_voice.wav", "dur": round(dur, 2)}
    print(f"  voice: {dur:.1f} s")
json.dump(out, open(os.path.join(HERE, "stills_data.json"), "w", encoding="utf-8"), indent=1)
